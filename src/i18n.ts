export const DICTS: Record<Lang, Dict> = { it, en }
export const LANG_LABELS: Record<Lang, string> = { it: 'Italiano', en: 'English' }

const KEY = 'banana33:lang'

function initialLang(): Lang {
  try {
    const v = localStorage.getItem(KEY)
    if (v === 'it' || v === 'en') return v
  } catch {
    // nessuna preferenza salvata
  }
  return navigator.language.toLowerCase().startsWith('it') ? 'it' : 'en'
}

export const useLang = create<{ lang: Lang; setLang: (l: Lang) => void }>((set) => ({
  lang: initialLang(),
  setLang: (lang) => {
    try {
      localStorage.setItem(KEY, lang)
    } catch {
      // preferenza valida solo per questa sessione
    }
    document.documentElement.lang = lang
    set({ lang })
  },
}))

/** Dizionario della lingua corrente (si aggiorna al cambio lingua) */
export const useT = () => DICTS[useLang((s) => s.lang)]
/** Per codice fuori dai componenti */
export const getT = () => DICTS[useLang.getState().lang]
